RX = [(c, re.compile(r, re.M), h) for c, r, h in P]
MARK = re.compile(r"⟦/?#?\d+⟧")


def load(path):
    if path.endswith(".json"):
        return [(s["id"], s["text"]) for s in json.load(io.open(path, encoding="utf-8"))["segments"]]
    lines = io.open(path, encoding="utf-8-sig").read().split("\n")
    return [(f"L{i + 1}", l) for i, l in enumerate(lines) if l.strip()]


def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    segs = load(sys.argv[1])
    total, per_cat = 0, Counter()
    for sid, text in segs:
        text = MARK.sub("", text)
        hits = []
        for c, rx, h in RX:
            for m in rx.finditer(text):
                hits.append((c, m.group(0).strip(), h)); per_cat[c] += 1
        if hits and "--summary" not in sys.argv:
            print(f"[{sid}]")
            for c, w, h in hits: print(f"   {c}: «{w}» → {h}")
        total += len(hits)
    print(f"\n{total} hits in {len(segs)} segments" + ("" if not per_cat else ": " + "، ".join(f"{c} {n}" for c, n in per_cat.most_common())))


if __name__ == "__main__":
    main()
